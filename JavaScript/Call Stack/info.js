// Call Stack
// The call stack is responsible for executing JavaScript code.
// It follows the LIFO (Last In, First Out) principle.
// Important Points
// The call stack has an execution context for the global scope called the Global Execution Context.
// On top of the global execution context, a new execution context is created whenever a function is called.
// The last called context is destroyed first.
// Memory allocation for local variables and primitive data types happens in the call stack.