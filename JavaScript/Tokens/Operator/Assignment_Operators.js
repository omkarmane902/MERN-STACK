//! Assignment operators are used to assign values to variables.

// Addition Assignment (+=)
let x = 10;
x += 5;
console.log(x); // 15


// Subtraction Assignment (-=)
let x = 10;
x -= 3;
console.log(x); // 7

// Multiplication Assignment (*=)
let x = 10;
x *= 2;
console.log(x); // 20

// Division Assignment (/=)
let x = 10;
x /= 2;
console.log(x); // 5


// Modulus Assignment (%=)
let x = 10;
x %= 3;
console.log(x); // 1

// Exponentiation Assignment (**=)
let x = 2;
x **= 3;
console.log(x); // 8


// Real Example
let balance = 1000;
balance += 500; // Deposit 500
console.log(balance); // 1500