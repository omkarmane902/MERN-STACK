// an identifier is the names given by the programmer.

// such as variable name ,function name , object name

//! Rules for Identifiers in JavaScript

//? 1) Must begin with a letter, underscore (_), or dollar sign ($)

// let name;
// let _count;
// let $price;

//? 2) Cannot begin with a digit
//    let 123name;   // Invalid

//? 3) Can contain letters, digits, underscores, and dollar signs

// let student1;
// let user_name;
// let $total;


//? 4) Cannot contain spaces or special characters (except _ and $)

// let user name; // Invalid
// let user-name; // Invalid


//? 5) Cannot be a reserved keyword

// let class;    // Invalid
// let function; // Invalid

//? 6) Identifiers are case-sensitive

// let name = "John";
// let Name = "Alice";

// name and Name are different identifiers.