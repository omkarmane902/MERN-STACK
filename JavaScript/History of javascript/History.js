//! 2. All the Names of JavaScript
// Before it became the language we use today, it went through a few different names:
// Mocha (The initial code name chosen by the founder).
// LiveScript (The first official name used when it was shipped in early preview versions).
// JavaScript (The final marketing name, chosen to trick people into thinking it was related to the super-popular language Java).
// ECMAScript (The official, legal, and technical name used for the rulebook).

//! 3. What is ECMA? (Explained Simply)
// ECMA (pronounced "Ek-ma") stands for the European Computer Manufacturers Association. Today, they are simply called ECMA International.
// Think of ECMA as a Global Referee Committee for technology.

//! Why did ECMA get involved?
// In the late 1990s, JavaScript became incredibly popular. Microsoft saw this and decided to copy it, creating their own version called JScript for Internet Explorer.
// Because Netscape and Microsoft had different versions, a website that worked perfectly in Netscape would completely break in Internet Explorer. It was a nightmare for developers.
// To stop the fighting, Netscape handed JavaScript over to the ECMA committee in 1997. They told ECMA: "Please write an official rulebook so everyone has to build JavaScript the exact same way."

